const { Client, LocalAuth } = require("whatsapp-web.js");
const qrcode = require("qrcode-terminal");

const client = new Client({
  authStrategy: new LocalAuth(), // saves session so you don't re-scan QR every time
  puppeteer: {
    headless: true,
    args: ["--no-sandbox", "--disable-setuid-sandbox"],
  },
});

// ── QR code: scan this with WhatsApp to log in ──────────────────────────────
client.on("qr", (qr) => {
  console.log("\n📱 Scan this QR code in WhatsApp → Linked Devices → Link a device:\n");
  qrcode.generate(qr, { small: true });
});

client.on("ready", () => {
  console.log("✅ @Equb Draw Bot is online and ready!");
});

// ── Fisher-Yates shuffle ─────────────────────────────────────────────────────
function shuffle(array) {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// ── Listen for messages ──────────────────────────────────────────────────────
client.on("message", async (message) => {
  const chat = await message.getChat();

  // only respond in group chats
  if (!chat.isGroup) {
    message.reply("⚠️ I only work inside WhatsApp groups. Add me to a group and type /draw there!");
    return;
  }

  const text = message.body.trim().toLowerCase();

  // ── /draw command ──────────────────────────────────────────────────────────
  if (text === "/draw") {
    await chat.sendStateTyping();

    // fetch all group participants
    const participants = chat.participants;

    if (participants.length < 2) {
      message.reply("⚠️ Not enough members to run a draw.");
      return;
    }

    // resolve display names for each participant
    const names = await Promise.all(
      participants.map(async (p) => {
        try {
          const contact = await client.getContactById(p.id._serialized);
          // prefer saved name → push name → phone number
          return contact.name || contact.pushname || contact.number;
        } catch {
          return p.id.user; // fallback to raw number
        }
      })
    );

    // shuffle and build result message
    const shuffled = shuffle(names);
    const N = shuffled.length;

    const lines = shuffled.map((name, i) => `${i + 1}. ${name}`);

    const result = [
      `🎱 *Equb Draw Results*`,
      `━━━━━━━━━━━━━━━━━━━━━`,
      ...lines,
      `━━━━━━━━━━━━━━━━━━━━━`,
      `👥 *${N} members* drawn randomly`,
      `🤖 _Generated by @Equb Draw Bot_`,
    ].join("\n");

    chat.sendMessage(result);
    return;
  }

  // ── /help command ──────────────────────────────────────────────────────────
  if (text === "/help") {
    message.reply(
      `🤖 *Equb Draw Bot Commands*\n\n` +
      `/draw  — Randomly assign numbers 1 to N to all group members\n` +
      `/help  — Show this message`
    );
  }
});

client.initialize();
